import type { TurnResult } from "../agent/run-turn.ts";
import { MANUAL_VOICE_SCENARIO, type Scenario } from "./scenarios.ts";

export interface ScenarioOutcome {
  scenario: Scenario;
  results: TurnResult[];
  tickets: Record<string, unknown>[];
  escalations: Record<string, unknown>[];
  checks: { name: string; passed: boolean; detail: string | null }[];
  passed: boolean;
  notes: string;
  conversationId: string;
  actual: string;
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();

function toolsAndRecords(o: ScenarioOutcome): string {
  const tools = [...new Set(o.results.flatMap((t) => t.toolsUsed))];
  const parts = [`Tools: ${tools.length ? tools.map((t) => `\`${t}\``).join(", ") : "none"}`];
  if (o.tickets.length) parts.push(`Ticket: ${o.tickets.map((t) => `\`${t.ticket_ref}\``).join(", ")}`);
  if (o.escalations.length) parts.push(`Escalation: ${o.escalations.map((e) => `\`${e.escalation_ref}\` (${e.category})`).join(", ")}`);
  parts.push(`Conversation: \`${o.conversationId.slice(0, 8)}\``);
  return parts.join("<br>");
}

function actualSummary(o: ScenarioOutcome): string {
  return o.results
    .map((t, i) => `${o.results.length > 1 ? `T${i + 1} ` : ""}(${t.answerType}) "${t.reply}"`)
    .join("<br>");
}

export function renderEvidence(input: {
  runId: string;
  model: string;
  date: Date;
  outcomes: ScenarioOutcome[];
  counts: Record<string, number>;
}): string {
  const { runId, model, date, outcomes, counts } = input;
  const passed = outcomes.filter((o) => o.passed).length;
  const row = (o: ScenarioOutcome) =>
    [
      o.scenario.id,
      cell(o.scenario.prdArea),
      cell(o.scenario.turns.map((t, i) => (o.scenario.turns.length > 1 ? `T${i + 1}: ${t}` : t)).join("<br>")),
      cell(o.scenario.expected.join("<br>")),
      cell(actualSummary(o)),
      toolsAndRecords(o),
      o.passed ? "✅ Pass" : "❌ Fail",
      cell(o.passed ? `${o.checks.length}/${o.checks.length} automated checks passed.` : o.checks.filter((c) => !c.passed).map((c) => `${c.name}: ${c.detail}`).join("; ")),
    ].join(" | ");
  // The brief's scenarios (1–8), then its rows 9 (voice) and 10 (logging), then our extra scenarios.
  const fromBrief = (o: ScenarioOutcome) => Number(o.scenario.id) < 9;
  const rows = outcomes.filter(fromBrief).map(row);

  const voice = MANUAL_VOICE_SCENARIO;
  rows.push(
    [
      voice.id,
      voice.prdArea,
      cell(voice.input),
      cell(voice.expected.join("<br>")),
      "_To be filled in after a live call: question asked, what Koya said._",
      "_Vapi call ID; matching `conversations.vapi_call_id` row._",
      "⏳ Manual",
      "Needs a real microphone and Vapi; see README → Voice test.",
    ].join(" | "),
  );
  rows.push(
    [
      "10",
      "Logging",
      "All scenarios above",
      cell("Supabase contains conversation, retrieval, MCP tool-call, ticket, escalation, and evaluation records that match the test run."),
      cell(Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join("<br>")),
      `Run \`${runId.slice(0, 8)}\``,
      counts.conversations === outcomes.length && counts.evaluations === outcomes.length && (counts.tool_call_logs ?? 0) > 0 && (counts.retrieval_logs ?? 0) > 0 ? "✅ Pass" : "❌ Fail",
      "Counts are for this run's eval conversations only (filter by conversation or `evaluations.run_id`).",
    ].join(" | "),
  );
  rows.push(...outcomes.filter((o) => !fromBrief(o)).map(row));

  const transcripts = outcomes
    .map((o) => {
      const lines = o.scenario.turns.flatMap((t, i) => {
        const r = o.results[i];
        return [
          `- **Caller:** ${t}`,
          `- **Koya** _(${r?.answerType}${r?.confidence ? `, ${r.confidence}` : ""}; tools: ${r?.toolsUsed.join(", ") || "none"}; first words ${r?.firstTextMs ?? "–"} ms)_: ${r?.reply ?? ""}`,
        ];
      });
      const checks = o.checks.map((c) => `  - ${c.passed ? "✅" : "❌"} ${c.name}${c.detail ? ` — ${c.detail}` : ""}`);
      return [`### ${o.scenario.id}. ${o.scenario.name}`, "", ...lines, "", "<details><summary>Checks</summary>", "", ...checks, "", "</details>", ""].join("\n");
    })
    .join("\n");

  return `# Koya — Testing Evidence

Generated by \`pnpm eval\` on ${date.toISOString().slice(0, 16).replace("T", " ")} UTC · model \`${model}\` · run \`${runId}\` · **${passed}/${outcomes.length} automated scenarios passed**

Each scenario from \`assets/test-scenarios.md\` ran against the live agent in text mode (same agent core, MCP server and Supabase database as the voice path). Results are stored in the Supabase \`evaluations\` table under this run ID, and each scenario has its own \`eval\` conversation, so its turns, retrievals, tool calls, tickets and escalations can be inspected directly.

| # | Test area | Test input | Expected behavior | Actual behavior | Tools / records | Result | Notes |
| --- | --- | --- | --- | --- | --- | --- | --- |
${rows.map((r) => `| ${r} |`).join("\n")}

## Transcripts and checks

${transcripts}
`;
}
